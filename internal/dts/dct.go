package dts

// The 32-point fixed-point IMDCT of the synthesis filter (half of its
// output), as the reference decoder computes it.

func sumA(in, out []int32, n int) {
	for i := range n {
		out[i] = in[2*i] + in[2*i+1]
	}
}

func sumB(in, out []int32, n int) {
	out[0] = in[0]
	for i := 1; i < n; i++ {
		out[i] = in[2*i] + in[2*i-1]
	}
}

func sumC(in, out []int32, n int) {
	for i := range n {
		out[i] = in[2*i]
	}
}

func sumD(in, out []int32, n int) {
	out[0] = in[1]
	for i := 1; i < n; i++ {
		out[i] = in[2*i-1] + in[2*i+1]
	}
}

