func dctA(in, out []int32) {
	for i := range 8 {
		var r int64
		for j := range 8 {
			r += int64(cosModA[i][j]) * int64(in[j])
		}
		out[i] = norm(r, 23)
	}
}

func dctB(in, out []int32) {
	for i := range 8 {
		r := int64(in[0]) << 23
		for j := range 7 {
			r += int64(cosModB[i][j]) * int64(in[1+j])
		}
		out[i] = norm(r, 23)
	}
}

var modACos = [16]int32{
	4199362, 4240198, 4323885, 4454708, 4639772, 4890013, 5221943, 5660703,
	-6245623, -7040975, -8158494, -9809974, -12450076, -17261920, -28585092, -85479984,
}

func modA(in, out []int32) {
	for i := range 8 {
		out[i] = mul23(modACos[i], in[i]+in[8+i])
	}
	for i, k := 8, 7; i < 16; i, k = i+1, k-1 {
		out[i] = mul23(modACos[i], in[k]-in[8+k])
	}
}

var modBCos = [8]int32{4214598, 4383036, 4755871, 5425934, 6611520, 8897610, 14448934, 42791536}

func modB(in, out []int32) {
	for i := range 8 {
		in[8+i] = mul23(modBCos[i], in[8+i])
	}
	for i := range 8 {
		out[i] = in[i] + in[8+i]
	}
	for i, k := 8, 7; i < 16; i, k = i+1, k-1 {
		out[i] = in[k] - in[8+k]
	}
}

