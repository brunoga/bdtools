func modC(in, out []int32) {
	for i := range 16 {
		out[i] = mul23(modCCos[i], in[i]+in[16+i])
	}
	for i, k := 16, 15; i < 32; i, k = i+1, k-1 {
		out[i] = mul23(modCCos[i], in[k]-in[16+k])
	}
}

func clipV(v []int32) {
	for i := range v {
		v[i] = clip23(v[i])
	}
}

func imdctHalf32(out []int32, in *[32]int32) {
	var a, b [32]int32
	var mag int64
	for _, v := range in {
		if v < 0 {
			mag -= int64(v)
		} else {
			mag += int64(v)
		}
	}
	shift, round := 0, int32(0)
	if mag > 0x400000 {
		shift, round = 2, 2
	}
	for i, v := range in {
		a[i] = (v + round) >> shift
	}
	sumA(a[:], b[0:], 16)
	sumB(a[:], b[16:], 16)
	clipV(b[:])
	sumA(b[0:], a[0:], 8)
	sumB(b[0:], a[8:], 8)
	sumC(b[16:], a[16:], 8)
	sumD(b[16:], a[24:], 8)
	clipV(a[:])
	dctA(a[0:], b[0:])
	dctB(a[8:], b[8:])
	dctB(a[16:], b[16:])
	dctB(a[24:], b[24:])
	clipV(b[:])
	modA(b[0:], a[0:])
	modB(b[16:], a[16:])
	clipV(a[:])
	modC(a[:], b[:])
	for i := range b {
		b[i] = clip23(b[i] << shift)
	}
	for i, k := 0, 31; i < 16; i, k = i+1, k-1 {
		out[i] = clip23(b[i] - b[k])
		out[16+i] = clip23(b[i] + b[k])
	}
}
