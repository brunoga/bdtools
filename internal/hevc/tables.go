// Up-right diagonal scans (6.5.3): (x, y) of each scan position.
var (
	diagScan2x2 = [4][2]uint8{{0, 0}, {0, 1}, {1, 0}, {1, 1}}
	diagScan4x4 = makeDiagScan(4)
	diagScan8x8 = makeDiagScan(8)
)

func makeDiagScan(n int) [][2]uint8 {
	out := make([][2]uint8, 0, n*n)
	x, y := 0, 0
	for len(out) < n*n {
		for y >= 0 {
			if x < n && y < n {
				out = append(out, [2]uint8{uint8(x), uint8(y)})
			}
			y--
			x++
		}
		y = x
		x = 0
	}
	return out
}

// Horizontal and vertical scans of a 4x4 sub-block (and of the 2x2
// sub-blocks of an 8x8 block).
var (
	horizScan4x4 = makeHorizScan(4)
	vertScan4x4  = makeVertScan(4)
	horizScan2x2 = makeHorizScan(2)
	vertScan2x2  = makeVertScan(2)
)

func makeHorizScan(n int) [][2]uint8 {
	out := make([][2]uint8, 0, n*n)
	for y := range n {
		for x := range n {
			out = append(out, [2]uint8{uint8(x), uint8(y)})
		}
	}
	return out
}

func makeVertScan(n int) [][2]uint8 {
	out := make([][2]uint8, 0, n*n)
	for x := range n {
		for y := range n {
			out = append(out, [2]uint8{uint8(x), uint8(y)})
		}
	}
	return out
}

