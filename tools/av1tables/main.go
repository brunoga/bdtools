// Command av1tables turns the AV1 specification's constants, enumerations
// and constant lookup tables into Go source for package av1:
//
//	go run ./tools/av1tables -spec ~/mvc-scratch/av1/av1-spec -out internal/av1
//
// -spec is a clone of the specification's Markdown source
// (github.com/AOMediaCodec/av1-spec). Two files are written:
//
//   - consts_gen.go: every constant of the symbols section (03), every
//     enumeration of the semantics section (the "| value | Name of ..."
//     tables of 07) and the constants defined in tables elsewhere (the
//     wedge directions and sinpi values of 08), with the spec's names, as
//     untyped constants; and the named element types of the tables whose
//     values are enumeration names.
//   - tables_gen.go: every constant array written in C in the code blocks
//     of sections 06 to 10 and the annexes (Name[ dims ] = { ... }), as a
//     package-level var with a lower camel case name (Default_Y_Mode_Cdf
//     becomes defaultYModeCdf), its dimensions the spec's expressions, its
//     values exactly the spec's (CDFs keep their trailing count), plus the
//     tables the spec defines by formula (Block_Width, Block_Height).
//
// The generator checks every table's element count against its evaluated
// dimensions and every CDF row (non-decreasing, ending 32768 then 0), and
// fails on a name defined twice with different values. Its output depends
// on nothing but the spec text.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

const header = "// Code generated by tools/av1tables from the AV1 specification. DO NOT EDIT.\n\npackage av1\n\n"

// Sections the generator reads, in order.
var (
	symbolFiles = []string{"03.symbols.md"}
	enumFiles   = []string{"06.bitstream.syntax.md", "07.bitstream.semantics.md", "08.decoding.process.md", "09.parsing.process.md", "10.additional.tables.md"}
	tableFiles  = []string{"06.bitstream.syntax.md", "07.bitstream.semantics.md", "08.decoding.process.md", "09.parsing.process.md", "10.additional.tables.md", "annex.a.levels.md", "annex.b.superframes.md", "annex.d.large.scale.tile.md", "annex.e.decoder.model.md"}
)

// enumTypes gives the named element type of a table whose values are all
// names of one of these families.
var enumTypes = []struct {
	name, under string
	re          *regexp.Regexp
}{
	{"blockSize", "uint8", regexp.MustCompile(`^BLOCK_(\d+X\d+|INVALID)$`)},
	{"txSize", "uint8", regexp.MustCompile(`^TX_\d+X\d+$`)},
	{"txType", "uint8", regexp.MustCompile(`^(IDTX|(DCT|ADST|FLIPADST)_(DCT|ADST|FLIPADST)|[VH]_(DCT|ADST|FLIPADST))$`)},
	{"predictionMode", "uint8", regexp.MustCompile(`^(DC|V|H|D\d+|SMOOTH|SMOOTH_V|SMOOTH_H|PAETH|UV_CFL)_PRED$`)},
	{"restorationType", "uint8", regexp.MustCompile(`^RESTORE_[A-Z]+$`)},
	{"refFrame", "int8", regexp.MustCompile(`^(NONE|INTRA_FRAME|LAST[23]?_FRAME|GOLDEN_FRAME|BWDREF_FRAME|ALTREF2?_FRAME)$`)},
	{"wedgeDirection", "uint8", regexp.MustCompile(`^WEDGE_(HORIZONTAL|VERTICAL|OBLIQUE\d+)$`)},
}

// typeGroups are families of tables used interchangeably (get_scan returns
// any scan; the Wiener and self guided bounds are read together): every
// table of a family gets the integer type that holds all their values.
var typeGroups = []*regexp.Regexp{
	regexp.MustCompile(`^(Default|Mrow|Mcol)_Scan_`),
	regexp.MustCompile(`^Wiener_Taps_`),
	regexp.MustCompile(`^Sgrproj_Xqd_`),
	regexp.MustCompile(`^Obmc_Mask_`),
	regexp.MustCompile(`^Sm_Weights_Tx_`),
	regexp.MustCompile(`^Wedge_Master_`),
	regexp.MustCompile(`^Segmentation_Feature_`),
	regexp.MustCompile(`^(Dc|Ac)_Qlookup$`),
	regexp.MustCompile(`^Cdef_(Pri|Sec)_Taps$`),
	regexp.MustCompile(`^(Mi_Width_Log2|Mi_Height_Log2|Num_4x4_Blocks_Wide|Num_4x4_Blocks_High|Block_Width|Block_Height)$`),
	regexp.MustCompile(`^Tx_(Width|Height)(_Log2)?$`),
}

// A constant is one named integer of the spec.
type constant struct {
	name  string
	expr  *node // its value as the spec writes it
	where string
	group string // the table it comes from, for the comment
}

// A table is one constant array of the spec.
type table struct {
	name   string // the spec's name
	dims   []*node
	init   *node // a list node
	where  string
	goType string // element type
	derive string // for a table defined by formula, its comment
}

// node is an expression or an initializer list.
type node struct {
	op       string // "num", "id", "list", unary "u-", "u+", or a binary operator
	val      int64  // for "num"
	text     string // for "num" and "id"
	kids     []*node
	children []*node // for "list"
}

type generator struct {
	consts   []*constant
	byName   map[string]*constant
	tables   []*table
	tabNames map[string]*table
	notes    []string
}

func main() {
	spec := flag.String("spec", "", "directory of the AV1 specification's Markdown source")
	out := flag.String("out", "internal/av1", "directory to write the generated Go files to")
	flag.Parse()
	if *spec == "" {
		fmt.Fprintln(os.Stderr, "av1tables: -spec is required")
		os.Exit(2)
	}
	if err := run(os.DirFS(*spec), *out); err != nil {
		fmt.Fprintln(os.Stderr, "av1tables:", err)
		os.Exit(1)
	}
}

func run(spec fs.FS, out string) error {
	g := &generator{byName: map[string]*constant{}, tabNames: map[string]*table{}}
	for _, f := range symbolFiles {
		if err := g.readMarkdownTables(spec, f, true); err != nil {
			return err
		}
	}
	for _, f := range enumFiles {
		if err := g.readMarkdownTables(spec, f, false); err != nil {
			return err
		}
	}
	for _, f := range tableFiles {
		if err := g.readCodeTables(spec, f); err != nil {
			return err
		}
	}
	if err := g.readDerivedTables(spec, "10.additional.tables.md"); err != nil {
		return err
	}
	if err := g.check(); err != nil {
		return err
	}
	consts, err := g.emitConsts()
	if err != nil {
		return err
	}
	tables, err := g.emitTables()
	if err != nil {
		return err
	}
	if err := writeFile(filepath.Join(out, "consts_gen.go"), consts); err != nil {
		return err
	}
	if err := writeFile(filepath.Join(out, "tables_gen.go"), tables); err != nil {
		return err
	}
	for _, n := range g.notes {
		fmt.Fprintln(os.Stderr, "note:", n)
	}
	nEnum := 0
	for _, c := range g.consts {
		if !strings.HasPrefix(c.where, "03") {
			nEnum++
		}
	}
	fmt.Fprintf(os.Stderr, "av1tables: %d constants (%d from 03.symbols.md, %d from enumeration and constant tables), %d tables\n",
		len(g.consts), len(g.consts)-nEnum, nEnum, len(g.tables))
	return nil
}

func writeFile(path string, src []byte) error {
	formatted, err := format.Source(src)
	if err != nil {
		return fmt.Errorf("%s: gofmt: %w", path, err)
	}
	return os.WriteFile(path, formatted, 0o644) //nolint:gosec // Go source, read by everyone
}

// ---------------------------------------------------------------------------
// Markdown tables: constants and enumerations.

var (
	constNameRe = regexp.MustCompile(`^[A-Z][A-Z0-9_]*$`)
	enumNameRe  = regexp.MustCompile(`^[A-Z][A-Z0-9_]*h?$`) // SCALABILITY_L2T1h
	intRe       = regexp.MustCompile(`^-?\d+$`)
	sepRowRe    = regexp.MustCompile(`^[\s|:\-]+$`)
)

func splitRow(line string) []string {
	s := strings.TrimSpace(line)
	s = strings.TrimPrefix(s, "|")
	s = strings.TrimSuffix(s, "|")
	cells := strings.Split(s, "|")
	for i := range cells {
		cells[i] = strings.TrimSpace(cells[i])
	}
	return cells
}

func unescape(s string) string {
	s = strings.ReplaceAll(s, "`", "")
	s = strings.ReplaceAll(s, `\<`, "<")
	s = strings.ReplaceAll(s, `\>`, ">")
	return strings.TrimSpace(s)
}

// readMarkdownTables reads the constant tables of a section: with symbols,
// the "| `NAME` | value | description" tables of 03; otherwise the
// "| value | Name of x" enumerations and "| Constant | Value" tables.
func (g *generator) readMarkdownTables(spec fs.FS, file string, symbols bool) error {
	data, err := fs.ReadFile(spec, file)
	if err != nil {
		return err
	}
	lines := strings.Split(string(data), "\n")
	inCode := false
	for i := 0; i < len(lines); i++ {
		if isFence(lines[i]) {
			inCode = !inCode
			continue
		}
		if inCode || !strings.HasPrefix(strings.TrimSpace(lines[i]), "|") {
			continue
		}
		start := i
		var rows [][]string
		for ; i < len(lines) && strings.HasPrefix(strings.TrimSpace(lines[i]), "|"); i++ {
			rows = append(rows, splitRow(lines[i]))
		}
		if len(rows) < 3 || !sepRowRe.MatchString(strings.Join(rows[1], "|")) {
			continue
		}
		hdr := rows[0]
		where := fmt.Sprintf("%s:%d", file, start+1)
		nameCol, valCol := -1, -1
		named := false // an enumeration: integer values only
		for c, h := range hdr {
			switch strings.Trim(h, "* ") {
			case "Symbol name", "Constant", "Symbol":
				nameCol = c
			case "Value":
				valCol = c
			}
		}
		if nameCol < 0 || valCol < 0 {
			if symbols {
				continue
			}
			nameCol = -1
			for c, h := range hdr {
				if strings.HasPrefix(h, "Name of") {
					if nameCol >= 0 { // a mapping between two enumerations
						nameCol = -2
						break
					}
					nameCol = c
				}
			}
			if nameCol < 1 {
				if nameCol == -2 {
					g.notes = append(g.notes, fmt.Sprintf("%s: table %q maps names to names, not an enumeration: skipped", where, strings.Join(hdr, " | ")))
				}
				continue
			}
			valCol = nameCol - 1
			named = true
		}
		group := strings.Join(hdr, " | ")
		for r, row := range rows[2:] {
			if len(row) <= nameCol || len(row) <= valCol {
				continue
			}
			rowWhere := fmt.Sprintf("%s:%d", file, start+3+r)
			name := unescape(row[nameCol])
			val := unescape(row[valCol])
			if named {
				// "NONE (this block uses single prediction)", "OBU_SEQUENCE_HEADER."
				if f := strings.Fields(name); len(f) > 0 {
					name = f[0]
				}
				if strings.HasSuffix(name, ".") {
					g.notes = append(g.notes, fmt.Sprintf("%s: %q written with a trailing period; read as %s", rowWhere, name, strings.TrimSuffix(name, ".")))
					name = strings.TrimSuffix(name, ".")
				}
				if !enumNameRe.MatchString(name) || !intRe.MatchString(val) {
					continue
				}
			} else if !constNameRe.MatchString(name) {
				continue
			}
			expr, err := parseExpr(val)
			if err != nil {
				return fmt.Errorf("%s: %s = %q: %w", rowWhere, name, val, err)
			}
			if err := g.addConst(&constant{name: name, expr: expr, where: rowWhere, group: group}); err != nil {
				return err
			}
		}
		i--
	}
	return nil
}

func (g *generator) addConst(c *constant) error {
	if old, ok := g.byName[c.name]; ok {
		if render(old.expr) == render(c.expr) {
			return nil
		}
		ov, err1 := g.eval(old.expr)
		nv, err2 := g.eval(c.expr)
		if err1 == nil && err2 == nil && ov == nv {
			return nil
		}
		return fmt.Errorf("%s defined as %s at %s and as %s at %s", c.name, render(old.expr), old.where, render(c.expr), c.where)
	}
	g.byName[c.name] = c
	g.consts = append(g.consts, c)
	return nil
}

func isFence(line string) bool {
	return strings.HasPrefix(strings.TrimSpace(line), "~~~~")
}

// ---------------------------------------------------------------------------
// C code blocks: constant arrays.

var (
	blockCommentRe = regexp.MustCompile(`(?s)/\*.*?\*/`)
	lineCommentRe  = regexp.MustCompile(`//[^\n]*`)
	tableNameRe    = regexp.MustCompile(`^[A-Z][A-Za-z0-9]*(_[A-Za-z0-9]+)*$`)
)

func (g *generator) readCodeTables(spec fs.FS, file string) error {
	data, err := fs.ReadFile(spec, file)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil
		}
		return err
	}
	lines := strings.Split(string(data), "\n")
	for i := 0; i < len(lines); i++ {
		if !isFence(lines[i]) {
			continue
		}
		start := i + 2 // the 1-based number of the block's first line
		var b strings.Builder
		for i++; i < len(lines) && !isFence(lines[i]); i++ {
			b.WriteString(lines[i])
			b.WriteByte('\n')
		}
		if err := g.scanBlock(b.String(), file, start); err != nil {
			return err
		}
	}
	return nil
}

// scanBlock finds every "Name[ dims ]... = { ... }" in a code block.
func (g *generator) scanBlock(code, file string, firstLine int) error {
	code = blockCommentRe.ReplaceAllStringFunc(code, func(s string) string {
		return strings.Repeat("\n", strings.Count(s, "\n")) // keep line numbers
	})
	code = lineCommentRe.ReplaceAllString(code, "")
	toks, err := tokenize(code)
	if err != nil {
		return fmt.Errorf("%s:%d: %w", file, firstLine, err)
	}
	for i := 0; i < len(toks); i++ {
		t := toks[i]
		if t.kind != tokID || !tableNameRe.MatchString(t.text) || !strings.ContainsAny(t.text, "abcdefghijklmnopqrstuvwxyz") {
			continue
		}
		if i > 0 && (toks[i-1].text == "." || toks[i-1].kind == tokID) {
			continue
		}
		// Dimensions.
		j := i + 1
		var dims []*node
		ok := true
		for j < len(toks) && toks[j].text == "[" {
			end := matchBracket(toks, j, "[", "]")
			if end < 0 {
				ok = false
				break
			}
			d, err := parseTokens(toks[j+1 : end])
			if err != nil {
				ok = false
				break
			}
			dims = append(dims, d)
			j = end + 1
		}
		if !ok || len(dims) == 0 || j+1 >= len(toks) || toks[j].text != "=" || toks[j+1].text != "{" {
			continue
		}
		end := matchBracket(toks, j+1, "{", "}")
		where := fmt.Sprintf("%s:%d", file, firstLine+t.line)
		if end < 0 {
			return fmt.Errorf("%s: %s: unbalanced initializer", where, t.text)
		}
		init, missing, err := parseInit(toks[j+1 : end+1])
		if err != nil {
			return fmt.Errorf("%s: %s: %w", where, t.text, err)
		}
		for _, l := range missing {
			g.notes = append(g.notes, fmt.Sprintf("%s:%d: %s: comma missing at the end of the line; read as if present", file, firstLine+l, t.text))
		}
		tb := &table{name: t.text, dims: dims, init: init, where: where}
		if old, ok := g.tabNames[tb.name]; ok {
			if renderType(old) == renderType(tb) && render(old.init) == render(tb.init) {
				g.notes = append(g.notes, fmt.Sprintf("%s: %s repeats %s identically", where, tb.name, old.where))
			} else {
				return fmt.Errorf("%s: %s already defined differently at %s", where, tb.name, old.where)
			}
		} else {
			g.tabNames[tb.name] = tb
			g.tables = append(g.tables, tb)
		}
		i = end
	}
	return nil
}

var derivedRe = regexp.MustCompile(`(?m)^([A-Z][A-Za-z0-9_]*)\[ x \] is defined to be equal to (\d+) \* ([A-Z][A-Za-z0-9_]*)\[ x \]\.`)

// readDerivedTables defines the tables the spec gives by formula
// ("Block_Width[ x ] is defined to be equal to 4 * Num_4x4_Blocks_Wide[ x ].").
func (g *generator) readDerivedTables(spec fs.FS, file string) error {
	data, err := fs.ReadFile(spec, file)
	if err != nil {
		return err
	}
	for _, m := range derivedRe.FindAllStringSubmatchIndex(string(data), -1) {
		s := string(data)
		name, k, src := s[m[2]:m[3]], s[m[4]:m[5]], s[m[6]:m[7]]
		base, ok := g.tabNames[src]
		if !ok || len(base.dims) != 1 {
			return fmt.Errorf("%s: %s derived from unknown or multi-dimensional %s", file, name, src)
		}
		if _, dup := g.tabNames[name]; dup {
			continue
		}
		kv, _ := strconv.ParseInt(k, 10, 64)
		init := &node{op: "list"}
		for _, c := range base.init.children {
			v, err := g.eval(c)
			if err != nil {
				return err
			}
			init.children = append(init.children, &node{op: "num", val: kv * v, text: strconv.FormatInt(kv*v, 10)})
		}
		line := 1 + strings.Count(s[:m[0]], "\n")
		tb := &table{name: name, dims: base.dims, init: init, where: fmt.Sprintf("%s:%d", file, line),
			derive: fmt.Sprintf("%s[ x ] = %s * %s[ x ]", name, k, src)}
		g.tabNames[name] = tb
		g.tables = append(g.tables, tb)
	}
	return nil
}

// ---------------------------------------------------------------------------
// Checks and element types.

func (g *generator) check() error {
	undefined := map[string]bool{}
	var walk func(n *node)
	walk = func(n *node) {
		if n.op == "id" && g.byName[n.text] == nil {
			undefined[n.text] = true
		}
		for _, k := range n.kids {
			walk(k)
		}
		for _, k := range n.children {
			walk(k)
		}
	}
	for _, c := range g.consts {
		walk(c.expr)
	}
	for _, tb := range g.tables {
		for _, d := range tb.dims {
			walk(d)
		}
		walk(tb.init)
	}
	if len(undefined) > 0 {
		return fmt.Errorf("undefined constants: %s", strings.Join(sortedKeys(undefined), ", "))
	}
	for _, c := range g.consts {
		if _, err := g.eval(c.expr); err != nil {
			return fmt.Errorf("%s (%s): %w", c.name, c.where, err)
		}
	}
	goNames := map[string]string{}
	for _, tb := range g.tables {
		gn := goName(tb.name)
		if other, ok := goNames[gn]; ok {
			return fmt.Errorf("%s and %s both become %s", other, tb.name, gn)
		}
		goNames[gn] = tb.name
		if _, ok := g.byName[gn]; ok {
			return fmt.Errorf("%s's Go name %s is a constant", tb.name, gn)
		}
		dims := make([]int64, len(tb.dims))
		for d, e := range tb.dims {
			v, err := g.eval(e)
			if err != nil {
				return fmt.Errorf("%s (%s): dimension %s: %w", tb.name, tb.where, render(e), err)
			}
			dims[d] = v
		}
		if err := checkShape(tb.init, dims, tb.name); err != nil {
			return fmt.Errorf("%s: %w", tb.where, err)
		}
		var leaves []*node
		collect(tb.init, &leaves)
		if strings.HasSuffix(tb.name, "_Cdf") {
			tb.goType = "uint16"
			if err := g.checkCdf(tb.init, tb.name); err != nil {
				return fmt.Errorf("%s: %w", tb.where, err)
			}
			continue
		}
		typ, err := g.elemType(leaves)
		if err != nil {
			return fmt.Errorf("%s (%s): %w", tb.name, tb.where, err)
		}
		tb.goType = typ
	}
	// One integer type per family.
	for _, re := range typeGroups {
		var leaves []*node
		var members []*table
		for _, tb := range g.tables {
			if re.MatchString(tb.name) && !isEnumType(tb.goType) {
				members = append(members, tb)
				collect(tb.init, &leaves)
			}
		}
		if len(members) == 0 {
			continue
		}
		typ, err := g.elemType(leaves)
		if err != nil {
			return err
		}
		for _, tb := range members {
			tb.goType = typ
		}
	}
	return nil
}

func isEnumType(name string) bool {
	for _, et := range enumTypes {
		if et.name == name {
			return true
		}
	}
	return false
}

func checkShape(n *node, dims []int64, path string) error {
	if n.op != "list" {
		return fmt.Errorf("%s: a value where a list of %d was expected", path, dims[0])
	}
	if int64(len(n.children)) != dims[0] {
		return fmt.Errorf("%s: %d elements, the dimension says %d", path, len(n.children), dims[0])
	}
	for i, c := range n.children {
		p := fmt.Sprintf("%s[%d]", path, i)
		if len(dims) > 1 {
			if err := checkShape(c, dims[1:], p); err != nil {
				return err
			}
		} else if c.op == "list" {
			return fmt.Errorf("%s: a list where a value was expected", p)
		}
	}
	return nil
}

func collect(n *node, out *[]*node) {
	if n.op != "list" {
		*out = append(*out, n)
		return
	}
	for _, c := range n.children {
		collect(c, out)
	}
}

func (g *generator) checkCdf(n *node, path string) error {
	if n.children[0].op == "list" {
		for i, c := range n.children {
			if err := g.checkCdf(c, fmt.Sprintf("%s[%d]", path, i)); err != nil {
				return err
			}
		}
		return nil
	}
	vals := make([]int64, len(n.children))
	for i, c := range n.children {
		v, err := g.eval(c)
		if err != nil {
			return err
		}
		vals[i] = v
	}
	k := len(vals)
	if k < 2 || vals[k-2] != 32768 || vals[k-1] != 0 {
		return fmt.Errorf("%s: CDF row %v does not end with 32768, 0", path, vals)
	}
	for i := 1; i < k-1; i++ {
		if vals[i] < vals[i-1] {
			return fmt.Errorf("%s: CDF row %v decreases", path, vals)
		}
	}
	return nil
}

// elemType picks a named type when every value is a name of one enum
// family, else the smallest integer type holding every value.
func (g *generator) elemType(leaves []*node) (string, error) {
	for _, et := range enumTypes {
		all := true
		for _, l := range leaves {
			if l.op != "id" || !et.re.MatchString(l.text) {
				all = false
				break
			}
		}
		if all {
			return et.name, nil
		}
	}
	lo, hi := int64(0), int64(0)
	for i, l := range leaves {
		v, err := g.eval(l)
		if err != nil {
			return "", err
		}
		if i == 0 || v < lo {
			lo = v
		}
		if i == 0 || v > hi {
			hi = v
		}
	}
	switch {
	case lo >= 0 && hi <= 255:
		return "uint8", nil
	case lo >= -128 && hi <= 127:
		return "int8", nil
	case lo >= 0 && hi <= 65535:
		return "uint16", nil
	case lo >= -32768 && hi <= 32767:
		return "int16", nil
	case lo >= -1<<31 && hi <= 1<<31-1:
		return "int32", nil
	}
	return "", fmt.Errorf("values %d..%d do not fit int32", lo, hi)
}

// usedEnumTypes lists the named types the tables use, in enumTypes order.
func (g *generator) usedEnumTypes() []int {
	used := map[string]bool{}
	for _, tb := range g.tables {
		used[tb.goType] = true
	}
	var idx []int
	for i, et := range enumTypes {
		if used[et.name] {
			idx = append(idx, i)
		}
	}
	return idx
}

// ---------------------------------------------------------------------------
// Output.

func (g *generator) emitConsts() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	group := ""
	for i, c := range g.consts {
		if c.group != group || i == 0 {
			if i > 0 {
				b.WriteString(")\n\n")
			}
			file, _, _ := strings.Cut(c.where, ":")
			fmt.Fprintf(&b, "// From %s, table %q.\nconst (\n", file, c.group)
			group = c.group
		}
		fmt.Fprintf(&b, "\t%s = %s\n", c.name, render(c.expr))
	}
	if len(g.consts) > 0 {
		b.WriteString(")\n")
	}
	if idx := g.usedEnumTypes(); len(idx) > 0 {
		b.WriteString("\n// Element types of the tables whose values are enumeration names.\ntype (\n")
		for _, i := range idx {
			fmt.Fprintf(&b, "\t%s %s\n", enumTypes[i].name, enumTypes[i].under)
		}
		b.WriteString(")\n")
	}
	return b.Bytes(), nil
}

func (g *generator) emitTables() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	for _, tb := range g.tables {
		file, _, _ := strings.Cut(tb.where, ":")
		if tb.derive != "" {
			fmt.Fprintf(&b, "// %s (%s: %s).\n", tb.name, file, tb.derive)
		} else {
			fmt.Fprintf(&b, "// %s (%s).\n", tb.name, file)
		}
		fmt.Fprintf(&b, "var %s = %s", goName(tb.name), renderType(tb))
		writeInit(&b, tb.init)
		b.WriteString("\n\n")
	}
	return b.Bytes(), nil
}

func renderType(tb *table) string {
	var s strings.Builder
	for _, d := range tb.dims {
		s.WriteString("[" + render(d) + "]")
	}
	s.WriteString(tb.goType)
	return s.String()
}

// writeInit writes an initializer: innermost lists of up to 16 values on a
// line, longer ones wrapped at 16 values.
func writeInit(b *bytes.Buffer, n *node) {
	if len(n.children) > 0 && n.children[0].op != "list" {
		if len(n.children) <= 16 {
			b.WriteByte('{')
			for i, c := range n.children {
				if i > 0 {
					b.WriteString(", ")
				}
				b.WriteString(render(c))
			}
			b.WriteByte('}')
			return
		}
		b.WriteString("{\n")
		for i, c := range n.children {
			b.WriteString(render(c))
			b.WriteByte(',')
			if i%16 == 15 || i == len(n.children)-1 {
				b.WriteByte('\n')
			} else {
				b.WriteByte(' ')
			}
		}
		b.WriteByte('}')
		return
	}
	b.WriteString("{\n")
	for _, c := range n.children {
		writeInit(b, c)
		b.WriteString(",\n")
	}
	b.WriteByte('}')
}

// goName turns a spec table name into lower camel case:
// Num_4x4_Blocks_Wide -> num4x4BlocksWide.
func goName(spec string) string {
	parts := strings.Split(spec, "_")
	var s strings.Builder
	for i, p := range parts {
		if p == "" {
			continue
		}
		if i == 0 {
			s.WriteString(strings.ToLower(p[:1]) + p[1:])
		} else {
			s.WriteString(strings.ToUpper(p[:1]) + p[1:])
		}
	}
	return s.String()
}

