// Expressions.

type tokKind int

const (
	tokNum tokKind = iota
	tokID
	tokOp
)

type token struct {
	kind tokKind
	text string
	val  int64
	line int
}

func tokenize(s string) ([]token, error) {
	var toks []token
	line := 0
	for i := 0; i < len(s); {
		c := s[i]
		switch {
		case c == '\n':
			line++
			i++
		case c == ' ' || c == '\t' || c == '\r':
			i++
		case c >= '0' && c <= '9':
			j := i
			for j < len(s) && (isAlnum(s[j])) {
				j++
			}
			text := s[i:j]
			v, err := strconv.ParseInt(strings.ReplaceAll(text, "_", ""), 0, 64)
			if err != nil {
				// Not a number (e.g. "4x4" outside an expression).
				toks = append(toks, token{kind: tokID, text: text, line: line})
			} else {
				toks = append(toks, token{kind: tokNum, text: text, val: v, line: line})
			}
			i = j
		case isAlnum(c):
			j := i
			for j < len(s) && isAlnum(s[j]) {
				j++
			}
			toks = append(toks, token{kind: tokID, text: s[i:j], line: line})
			i = j
		default:
			op := string(c)
			if i+1 < len(s) {
				two := s[i : i+2]
				switch two {
				case "<<", ">>", "==", "!=", "<=", ">=", "&&", "||", "++", "--", "+=", "-=":
					op = two
				}
			}
			toks = append(toks, token{kind: tokOp, text: op, line: line})
			i += len(op)
		}
	}
	return toks, nil
}

func isAlnum(c byte) bool {
	return c == '_' || c >= '0' && c <= '9' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z'
}

func matchBracket(toks []token, i int, open, close string) int {
	depth := 0
	for j := i; j < len(toks); j++ {
		switch toks[j].text {
		case open:
			depth++
		case close:
			depth--
			if depth == 0 {
				return j
			}
		}
	}
	return -1
}

func parseExpr(s string) (*node, error) {
	toks, err := tokenize(s)
	if err != nil {
		return nil, err
	}
	return parseTokens(toks)
}

func parseTokens(toks []token) (*node, error) {
	p := &parser{toks: toks}
	n, err := p.expr(0)
	if err != nil {
		return nil, err
	}
	if p.pos != len(toks) {
		return nil, fmt.Errorf("unexpected %q", toks[p.pos].text)
	}
	return n, nil
}

// parseInit parses a brace initializer whose elements are expressions. It
// also returns the lines that miss a comma between two elements.
func parseInit(toks []token) (*node, []int, error) {
	p := &parser{toks: toks}
	n, err := p.init()
	if err != nil {
		return nil, nil, err
	}
	if p.pos != len(toks) {
		return nil, nil, fmt.Errorf("unexpected %q after initializer", toks[p.pos].text)
	}
	return n, p.missingCommas, nil
}

type parser struct {
	toks          []token
	pos           int
	missingCommas []int // lines (relative to the code block) missing a comma
}

func (p *parser) peek() string {
	if p.pos < len(p.toks) {
		return p.toks[p.pos].text
	}
	return ""
}

func (p *parser) init() (*node, error) {
	if p.peek() != "{" {
		return p.expr(0)
	}
	p.pos++
	n := &node{op: "list"}
	for {
		if p.peek() == "}" {
			p.pos++
			return n, nil
		}
		c, err := p.init()
		if err != nil {
			return nil, err
		}
		n.children = append(n.children, c)
		switch p.peek() {
		case ",":
			p.pos++
		case "}":
		default:
			// A missing comma at the end of a line (Split_Tx_Size after
			// TX_32X32): the next element starts on a new line.
			if p.pos > 0 && p.pos < len(p.toks) && p.toks[p.pos].line > p.toks[p.pos-1].line && p.peek() != "" {
				p.missingCommas = append(p.missingCommas, p.toks[p.pos-1].line)
				continue
			}
			return nil, fmt.Errorf("unexpected %q in initializer", p.peek())
		}
	}
}

var precedence = map[string]int{"<<": 1, ">>": 1, "+": 2, "-": 2, "*": 3, "/": 3, "%": 3}

func (p *parser) expr(minPrec int) (*node, error) {
	lhs, err := p.unary()
	if err != nil {
		return nil, err
	}
	for {
		op := p.peek()
		prec, ok := precedence[op]
		if !ok || prec <= minPrec {
			return lhs, nil
		}
		p.pos++
		rhs, err := p.expr(prec)
		if err != nil {
			return nil, err
		}
		lhs = &node{op: op, kids: []*node{lhs, rhs}}
	}
}

func (p *parser) unary() (*node, error) {
	if p.pos >= len(p.toks) {
		return nil, errors.New("unexpected end of expression")
	}
	t := p.toks[p.pos]
	p.pos++
	switch {
	case t.text == "-" || t.text == "+":
		x, err := p.unary()
		if err != nil {
			return nil, err
		}
		if x.op == "num" && t.text == "-" {
			return &node{op: "num", val: -x.val, text: "-" + x.text}, nil
		}
		return &node{op: "u" + t.text, kids: []*node{x}}, nil
	case t.text == "(":
		x, err := p.expr(0)
		if err != nil {
			return nil, err
		}
		if p.peek() != ")" {
			return nil, errors.New("missing )")
		}
		p.pos++
		return &node{op: "()", kids: []*node{x}}, nil
	case t.kind == tokNum:
		return &node{op: "num", val: t.val, text: t.text}, nil
	case t.kind == tokID && constNameRe.MatchString(t.text) || t.kind == tokID && enumNameRe.MatchString(t.text):
		return &node{op: "id", text: t.text}, nil
	}
	return nil, fmt.Errorf("unexpected %q", t.text)
}

func (g *generator) eval(n *node) (int64, error) {
	switch n.op {
	case "num":
		return n.val, nil
	case "id":
		c, ok := g.byName[n.text]
		if !ok {
			return 0, fmt.Errorf("undefined constant %s", n.text)
		}
		return g.eval(c.expr)
	case "()", "u+":
		return g.eval(n.kids[0])
	case "u-":
		v, err := g.eval(n.kids[0])
		return -v, err
	}
	a, err := g.eval(n.kids[0])
	if err != nil {
		return 0, err
	}
	b, err := g.eval(n.kids[1])
	if err != nil {
		return 0, err
	}
	switch n.op {
	case "+":
		return a + b, nil
	case "-":
		return a - b, nil
	case "*":
		return a * b, nil
	case "/", "%":
		if b == 0 {
			return 0, errors.New("division by zero")
		}
		if n.op == "/" {
			return a / b, nil
		}
		return a % b, nil
	case "<<":
		return a << uint(b), nil
	case ">>":
		return a >> uint(b), nil
	}
	return 0, fmt.Errorf("unknown operator %s", n.op)
}

// render writes an expression as Go source.
func render(n *node) string {
	switch n.op {
	case "num", "id":
		return n.text
	case "()":
		return "(" + render(n.kids[0]) + ")"
	case "u-", "u+":
		return n.op[1:] + render(n.kids[0])
	case "list":
		parts := make([]string, len(n.children))
		for i, c := range n.children {
			parts[i] = render(c)
		}
		return "{" + strings.Join(parts, ", ") + "}"
	}
	return render(n.kids[0]) + " " + n.op + " " + render(n.kids[1])
}

// sortedKeys is used for deterministic diagnostics.
func sortedKeys(m map[string]bool) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
