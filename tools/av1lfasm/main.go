// Command av1lfasm writes the AV1 encoder's loop filter kernel
// (internal/av1/lf_amd64.s): the sample filtering process (spec 7.14.6)
// for the four lines of an edge segment at once, a line a 32-bit lane.
//
//	go run ./tools/av1lfasm -dir internal/av1
//
// The kernel gathers the samples across the edge (as many each side as
// the filter reads) into frame slots, works out each lane's masks (filter
// or not, flat, flat2, high edge variance) as loopFilter.sample does,
// then the narrow filter's outputs and the wide filters' (their sums
// written out from wideFilter's windows, the samples beyond them the last
// ones), blends them by the masks and writes back the samples the
// filter's length may change.
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"
)

var b strings.Builder

func e(format string, a ...any) { fmt.Fprintf(&b, format+"\n", a...) }

// v and o are the slots of the samples (k from -7 to 6, p0 at -1, q0 at
// 0) and of their outputs.
func v(k int) string { return fmt.Sprintf("%d(SP)", (k+7)*16) }
func o(k int) string { return fmt.Sprintf("%d(SP)", 224+(k+7)*16) }

// The masks' slots: the narrow filter's lanes, the flat ones', the flat2
// ones', high edge variance (then the narrow lanes without it).
const (
	ns  = "448(SP)"
	f1  = "464(SP)"
	f2  = "480(SP)"
	hev = "496(SP)"
)

// absGT ors acc with |a - b| > thr (a and b slots, thr a register).
func absGT(a, bb, thr, acc string) {
	e("\tVMOVDQU %s, X8", a)
	e("\tVPSUBD %s, X8, X8", bb)
	e("\tVPABSD X8, X8")
	e("\tVPCMPGTD %s, X8, X8", thr)
	e("\tVPOR X8, %s, %s", acc, acc)
}

func clamp(r string) {
	e("\tVPMAXSD X13, %s, %s", r, r)
	e("\tVPMINSD X12, %s, %s", r, r)
}

// blend puts new in output k's lanes of mask.
func blend(mask, n string, k int) {
	e("\tVMOVDQU %s, X10", o(k))
	e("\tVMOVDQU %s, X11", mask)
	e("\tVPBLENDVB X11, %s, X10, X10", n)
	e("\tVMOVDQU X10, %s", o(k))
}

// wcoefs is wideFilter(n, n2)'s output i's samples and their weights.
func wcoefs(n, n2, i int) [][2]int {
	at := func(k int) int { return min(max(k, -(n+1)), n) }
	w := map[int]int{}
	var order []int
	add := func(k int) {
		if w[k] == 0 {
			order = append(order, k)
		}
		w[k]++
	}
	for j := -n; j <= n; j++ {
		add(at(i + j))
	}
	for j := -n2; j <= n2; j++ {
		add(at(i + j))
	}
	var out [][2]int
	for _, k := range order {
		out = append(out, [2]int{k, w[k]})
	}
	return out
}

// wide sums an output's samples into X9, rounded (X8) and shifted down.
func wide(coefs [][2]int, shift int) {
	first := true
	for _, c := range coefs {
		for range c[1] {
			if first {
				e("\tVMOVDQU %s, X9", v(c[0]))
				first = false
			} else {
				e("\tVPADDD %s, X9, X9", v(c[0]))
			}
		}
	}
	e("\tVPADDD X8, X9, X9")
	e("\tVPSRLD $%d, X9, X9", shift)
}

func broadcast(val int, r string) {
	e("\tMOVL $%d, AX", val)
	e("\tVMOVD AX, %s", r)
	e("\tVPBROADCASTD %s, %s", r, r)
}

func main() {
	dir := flag.String("dir", ".", "the internal/av1 directory")
	flag.Parse()
	e(`//go:build amd64 && !purego

#include "textflag.h"

// Code generated by av1lfasm (tools/av1lfasm). DO NOT EDIT.

// func lfSeg4AVX2(buf *uint16, step, across, flen, size int, limit, blimit, thresh, bd int)
// The sample filtering process (spec 7.14.6) for the 4 lines of an edge
// segment, a line a dword lane: buf at the first line's first sample after
// the edge, step the samples across the edge, across the lines'.
TEXT ·lfSeg4AVX2(SB), 0, $512-72
	MOVQ buf+0(FP), SI
	MOVQ step+8(FP), R8
	SHLQ $1, R8
	MOVQ across+16(FP), R9
	SHLQ $1, R9
	MOVQ flen+24(FP), R10
	MOVQ size+32(FP), R12
	MOVQ $2, R11
	CMPQ R10, $6
	JLT lodone
	MOVQ $3, R11
	CMPQ R10, $8
	JLT lodone
	MOVQ $4, R11
	CMPQ R10, $16
	JLT lodone
	MOVQ $7, R11
lodone:
	MOVQ R11, AX
	IMULQ R8, AX
	MOVQ SI, BX
	SUBQ AX, BX
	MOVQ $7, AX
	SUBQ R11, AX
	SHLQ $4, AX
	LEAQ 0(SP), DI
	ADDQ AX, DI
	MOVQ R11, CX
	SHLQ $1, CX
gather:
	MOVWLZX (BX), AX
	VMOVD AX, X0
	MOVWLZX (BX)(R9*1), AX
	VPINSRD $1, AX, X0, X0
	LEAQ (BX)(R9*2), DX
	MOVWLZX (DX), AX
	VPINSRD $2, AX, X0, X0
	MOVWLZX (DX)(R9*1), AX
	VPINSRD $3, AX, X0, X0
	VMOVDQU X0, (DI)
	VMOVDQU X0, 224(DI)
	ADDQ R8, BX
	ADDQ $16, DI
	DECQ CX
	JNZ gather
	MOVQ limit+40(FP), AX
	VMOVD AX, X10
	VPBROADCASTD X10, X10
	MOVQ blimit+48(FP), AX
	VMOVD AX, X11
	VPBROADCASTD X11, X11
	MOVQ thresh+56(FP), AX
	VMOVD AX, X12
	VPBROADCASTD X12, X12
	MOVQ bd+64(FP), CX
	MOVL $1, AX
	SHLL CX, AX
	VMOVD AX, X13
	VPBROADCASTD X13, X13`)
	// p1 X1, p0 X2, q0 X3, q1 X4; |p1-p0| X5, |q1-q0| X6; the violations X7
	e("\tVMOVDQU %s, X1\n\tVMOVDQU %s, X2\n\tVMOVDQU %s, X3\n\tVMOVDQU %s, X4", v(-2), v(-1), v(0), v(1))
	e(`	VPSUBD X2, X1, X5
	VPABSD X5, X5
	VPSUBD X3, X4, X6
	VPABSD X6, X6
	VPCMPGTD X10, X5, X7
	VPCMPGTD X10, X6, X8
	VPOR X8, X7, X7
	VPSUBD X3, X2, X8
	VPABSD X8, X8
	VPADDD X8, X8, X8
	VPSUBD X4, X1, X9
	VPABSD X9, X9
	VPSRLD $1, X9, X9
	VPADDD X9, X8, X8
	VPCMPGTD X11, X8, X8
	VPOR X8, X7, X7
	CMPQ R10, $6
	JLT maskdone`)
	absGT(v(-3), v(-2), "X10", "X7")
	absGT(v(2), v(1), "X10", "X7")
	e("\tCMPQ R10, $8\n\tJLT maskdone")
	absGT(v(-4), v(-3), "X10", "X7")
	absGT(v(3), v(2), "X10", "X7")
	e("maskdone:")
	e("\tVPCMPEQD X9, X9, X9\n\tVPXOR X9, X7, X7")
	// flat (sizes 8 and 16): X15 the flat lanes filtered
	e("\tVPXOR X15, X15, X15\n\tCMPQ R12, $8\n\tJLT flatdone")
	e("\tVPCMPGTD X13, X5, X14\n\tVPCMPGTD X13, X6, X8\n\tVPOR X8, X14, X14")
	absGT(v(-3), v(-1), "X13", "X14")
	absGT(v(2), v(0), "X13", "X14")
	e("\tCMPQ R10, $8\n\tJLT flat3")
	absGT(v(-4), v(-1), "X13", "X14")
	absGT(v(3), v(0), "X13", "X14")
	e("flat3:")
	e("\tVPANDN X7, X14, X15")
	e("flatdone:")
	e("\tVMOVDQU X15, %s", f1)
	e("\tVPANDN X7, X15, X9\n\tVMOVDQU X9, %s", ns)
	// flat2 (size 16)
	e("\tVPXOR X9, X9, X9\n\tCMPQ R12, $16\n\tJLT flat2done\n\tVPXOR X14, X14, X14")
	for _, k := range []int{-5, -6, -7} {
		absGT(v(k), v(-1), "X13", "X14")
	}
	for _, k := range []int{4, 5, 6} {
		absGT(v(k), v(0), "X13", "X14")
	}
	e("\tVPANDN X15, X14, X9")
	e("flat2done:")
	e("\tVMOVDQU X9, %s", f2)
	e("\tVPCMPGTD X12, X5, X8\n\tVPCMPGTD X12, X6, X9\n\tVPOR X9, X8, X8\n\tVMOVDQU X8, %s", hev)
	// the narrow filter: X14 0x80<<bd, X12 and X13 the signed range
	e(`	MOVQ bd+64(FP), CX
	MOVL $0x80, AX
	SHLL CX, AX
	VMOVD AX, X14
	VPBROADCASTD X14, X14
	ADDQ $7, CX
	MOVL $1, AX
	SHLL CX, AX
	MOVL AX, DX
	NEGL DX
	DECL AX
	VMOVD AX, X12
	VPBROADCASTD X12, X12
	VMOVD DX, X13
	VPBROADCASTD X13, X13
	VPSUBD X14, X1, X1
	VPSUBD X14, X2, X2
	VPSUBD X14, X3, X3
	VPSUBD X14, X4, X4`)
	e("\tVPSUBD X4, X1, X5")
	clamp("X5")
	e("\tVPAND %s, X5, X5", hev)
	e("\tVPSUBD X2, X3, X6\n\tVPADDD X6, X5, X5\n\tVPADDD X6, X5, X5\n\tVPADDD X6, X5, X5")
	clamp("X5")
	broadcast(4, "X8")
	e("\tVPADDD X8, X5, X6")
	clamp("X6")
	e("\tVPSRAD $3, X6, X6")
	broadcast(3, "X8")
	e("\tVPADDD X8, X5, X7")
	clamp("X7")
	e("\tVPSRAD $3, X7, X7")
	e("\tVPSUBD X6, X3, X9")
	clamp("X9")
	e("\tVPADDD X14, X9, X9")
	blend(ns, "X9", 0)
	e("\tVPADDD X7, X2, X9")
	clamp("X9")
	e("\tVPADDD X14, X9, X9")
	blend(ns, "X9", -1)
	broadcast(1, "X8")
	e("\tVPADDD X8, X6, X6\n\tVPSRAD $1, X6, X6")
	e("\tVMOVDQU %s, X8\n\tVMOVDQU %s, X15\n\tVPANDN X15, X8, X15\n\tVMOVDQU X15, %s", hev, ns, hev)
	e("\tVPSUBD X6, X4, X9")
	clamp("X9")
	e("\tVPADDD X14, X9, X9")
	blend(hev, "X9", 1)
	e("\tVPADDD X6, X1, X9")
	clamp("X9")
	e("\tVPADDD X14, X9, X9")
	blend(hev, "X9", -2)
	// the wide filters
	e("\tCMPQ R12, $8\n\tJLT done")
	broadcast(4, "X8")
	e("\tCMPQ R10, $6\n\tJNE wide8")
	for i := -2; i < 2; i++ {
		wide(wcoefs(2, 1, i), 3)
		blend(f1, "X9", i)
	}
	e("\tJMP done\nwide8:")
	for i := -3; i < 3; i++ {
		wide(wcoefs(3, 0, i), 3)
		blend(f1, "X9", i)
	}
	e("\tCMPQ R12, $16\n\tJLT done")
	broadcast(8, "X8")
	for i := -6; i < 6; i++ {
		wide(wcoefs(6, 1, i), 4)
		blend(f2, "X9", i)
	}
	e("done:")
	e(`	MOVQ $2, R11
	CMPQ R10, $8
	JLT wbset
	MOVQ $3, R11
	CMPQ R10, $16
	JLT wbset
	MOVQ $6, R11
wbset:
	MOVQ R11, AX
	IMULQ R8, AX
	MOVQ SI, BX
	SUBQ AX, BX
	MOVQ $7, AX
	SUBQ R11, AX
	SHLQ $4, AX
	LEAQ 224(SP), DI
	ADDQ AX, DI
	MOVQ R11, CX
	SHLQ $1, CX
scatter:
	VMOVDQU (DI), X0
	VMOVD X0, AX
	MOVW AX, (BX)
	VPEXTRD $1, X0, AX
	MOVW AX, (BX)(R9*1)
	LEAQ (BX)(R9*2), DX
	VPEXTRD $2, X0, AX
	MOVW AX, (DX)
	VPEXTRD $3, X0, AX
	MOVW AX, (DX)(R9*1)
	ADDQ R8, BX
	ADDQ $16, DI
	DECQ CX
	JNZ scatter
	RET`)
	if err := os.WriteFile(filepath.Join(*dir, "lf_amd64.s"), []byte(b.String()), 0o600); err != nil {
		log.Fatal(err)
	}
}
